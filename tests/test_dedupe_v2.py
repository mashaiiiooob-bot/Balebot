import os, random, sys, time
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
os.environ["TG_API_HASH"] = "x"
import dedupe
from dedupe import signature, is_duplicate, is_duplicate_v1

# پیکره‌ی اخیر (≥۵۰ پیام) که واژه‌های رایج روز در آن زیاد تکرار شده‌اند
rnd = random.Random(7)
COMMON = "حمله پهپادی مدارس تعطیلی فردا قیمت دلار سخنگوی دولت آلودگی هوا زخمی منطقه مواضع شلیک موشک سپاه بنزین".split()
now = time.time()
corpus = []
for i in range(110):
    txt = " ".join(rnd.sample(COMMON, 5)) + f" نام{i}"
    corpus.append({"t": int(now) - rnd.randint(0, 3000), **signature(txt)})
assert len(corpus) >= dedupe.MIN_DOCS

def old(*texts): return corpus + [{"t": int(now) - 300, **signature(t)} for t in texts]
def v2(new, entries): return is_duplicate(signature(new), entries, now)
def v1(new, entries): return is_duplicate_v1(signature(new), entries, now)

# ---- ۱) واژه‌ی مشترک زیاد، واقعه‌ی متفاوت → تکراری نیست (و نسخه‌ی قدیمی اشتباه می‌کرد)
cases_diff = [
    ("حمله پهپادی به اصفهان؛ دو نفر زخمی شدند", "حمله پهپادی به تبریز؛ سه نفر زخمی شدند"),      # مکان + عدد
    ("آلودگی هوا؛ مدارس تهران فردا تعطیل شد", "آلودگی هوا؛ مدارس کرج فردا تعطیل شد"),              # مکان
    ("سخنگوی دولت: قیمت بنزین تغییر نمی‌کند", "سخنگوی دولت: قیمت نان تغییر نمی‌کند"),             # جزئیات اختصاصیِ متفاوت
    ("آتش‌سوزی در پالایشگاه آبادان مهار شد", "آتش‌سوزی در پالایشگاه بندرعباس مهار شد"),
    ("تعطیلی مدارس شهر کرج فردا شنبه به دلیل آلودگی هوا اعلام شد", "تعطیلی مدارس تهران فردا"),    # تیتر کوتاه از شهر دیگر
    ("۲ نفر در تصادف جاده‌ای کشته شدند", "۵ نفر در تصادف جاده‌ای کشته شدند"),                     # عدد
    ("دو نفر در تصادف جاده‌ای کشته شدند", "سه نفر در تصادف جاده‌ای کشته شدند"),                     # عدد حروفی
]
v1_wrong = 0
for o, n in cases_diff:
    e = old(o)
    assert not v2(n, e), ("v2 اشتباهاً تکراری گرفت", o, n)
    v1_wrong += v1(n, e)
assert v1_wrong >= 3, v1_wrong   # نسخه‌ی قبلی روی همین موارد واقعاً اشتباه می‌کرد

# ---- ۲) تکراری واقعی (بازنویسی/املای متفاوت/تیتر خلاصه) → همچنان گرفته می‌شود
cases_dup = [
    ("سپاه پاسداران از شلیک موشک به مواضع مستقر در منطقه خبر داد", "خبر فوری: شلیك موشك به مواضع مستقر در منطقه توسط سپاه پاسداران"),
    ("حمله پهپادی به اصفهان؛ دو نفر زخمی شدند", "اصفهان: حمله‌ی پهپادی؛ ۲ زخمی"),
    ("آلودگی هوا؛ مدارس تهران فردا تعطیل شد", "مدارس تهران فردا به‌دلیل آلودگی هوا تعطیل است"),
    ("وزیر خارجه با سفیر چین درباره‌ی توافق جدید گفتگو کرد", "گفتگوی وزیر خارجه و سفیر چین درباره‌ی توافق جدید"),
]
for o, n in cases_dup:
    assert v2(n, old(o)), ("v2 تکراری واقعی را رد کرد", o, n)

# ---- ۳) تیتر کوتاهِ خبر مفصل: فقط وقتی واژه‌ی اختصاصی مشترک باشد
long_ = "وزیر خارجه با سفیر چین درباره‌ی توافق جدید هسته‌ای فردا در ژنو گفتگو می‌کند"
assert v2("توافق هسته‌ای وزیر خارجه با سفیر چین", old(long_))                       # اختصاصی مشترک: تکراری
assert not v2("تعطیلی مدارس فردا", old("تعطیلی مدارس شهر کرج فردا شنبه به دلیل آلودگی هوا اعلام شد"))   # فقط واژه‌های رایج
# ---- ۴) مکانِ زیرمجموعه تضاد نیست («تهران» در برابر «تهران و کرج»)
assert v2("مدارس تهران فردا تعطیل شد؛ آلودگی هوا", old("آلودگی هوا؛ مدارس تهران و کرج فردا تعطیل شد"))
# ---- ۵) پیکره‌ی کوچک (<۵۰): رفتار امن مثل قبل، با قفل مکان/عدد
small = [{"t": int(now) - 60, **signature("حمله پهپادی به اصفهان؛ دو نفر زخمی شدند")}]
assert not is_duplicate(signature("حمله پهپادی به تبریز؛ دو نفر زخمی شدند"), small, now)
assert is_duplicate(signature("حمله پهپادی به اصفهان؛ دو نفر زخمی شدند"), small, now)
# ---- ۶) ریشه‌ی «ان» برای مکان‌ها یکسان است (اصفهان ↔ اصفهانی)
assert signature("اصفهان")["p"] == signature("اصفهانی")["p"] != []
print("DEDUPE V2 OK")

# ---- لایه‌ی هوش مصنوعی فقط نامزدهای «بدون تضاد و با واژه‌ی اختصاصی مشترک» را می‌بیند
import tempfile
import poll
from state import State
st = State(tempfile.mkdtemp() + "/s.json")
st.data["seen"] = list(corpus)
def put(text):
    s = signature(text)
    poll.RECENT.append({"w": set(s["w"]), "n": set(s["n"]), "p": set(s["p"]), "text": text, "t": time.time()})
poll.RECENT.clear()
put("آلودگی هوا؛ مدارس تهران فردا تعطیل شد")
assert poll.ai_candidates(signature("آلودگی هوا؛ مدارس کرج فردا تعطیل شد"), time.time(), st) == []             # مکان متفاوت: AI دخالت نکند
assert len(poll.ai_candidates(signature("مدارس تهران فردا تعطیل شد؛ آلودگی هوا شدید است"), time.time(), st)) == 1  # هم‌واقعه
poll.RECENT.clear(); put("سخنگوی دولت: قیمت بنزین تغییر نمی‌کند")
assert poll.ai_candidates(signature("سخنگوی دولت: قیمت نان تغییر نمی‌کند"), time.time(), st) == []             # جزئیات متفاوت
poll.RECENT.clear()
print("AI CANDIDATES OK")
