import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))
from profanity import has_profanity, LEVELS

# هر واژه‌ی فهرست در چند قالب باید گرفته شود
for lvl, words in LEVELS.items():
    for w in words:
        for sample in (w, f"او گفت {w} و رفت", f"«{w}»"):
            assert has_profanity(sample, 1), (lvl, w, sample)
        assert has_profanity(w, lvl), (lvl, w)

